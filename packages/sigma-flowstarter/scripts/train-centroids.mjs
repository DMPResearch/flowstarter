#!/usr/bin/env node
/**
 * Build both heads' centroids from the synthetic multilingual phrase set.
 *
 *   pnpm --filter @flowstarter/sigma-flowstarter train
 *
 * Writes models/centroids.json and models/provenance.json. The encoder that
 * builds the centroids is the encoder that serves them — the whole file is
 * embedded with the same pinned q8 ONNX the runtime loads, because train/serve
 * skew in an embedding classifier is silent: all the numbers look fine, they
 * are just measured in a different space.
 *
 * Run `calibrate` afterwards. Centroids without a re-swept band are a band
 * calibrated against geometry that no longer exists.
 */

import { writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  LocalSentenceEncoder,
  loadEncoderConfig,
  trainCentroids,
} from '@flowstarter/sigma-core';
import { buildPhrases, phraseCounts } from '../src/training/phrases.ts';
import { LANGUAGES } from '../src/taxonomy.ts';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const version = process.env.SIGMA_CENTROIDS_VERSION ?? new Date().toISOString().slice(0, 10);

const encoderConfig = loadEncoderConfig();
const encoder = new LocalSentenceEncoder(encoderConfig);

const train = buildPhrases('train');
const holdout = buildPhrases('holdout');
console.log(
  `phrases : ${train.length} train / ${holdout.length} holdout, ` +
    `${LANGUAGES.length} languages, template-disjoint split`,
);
console.log(`encoder : ${encoderConfig.model}@${encoderConfig.revision} (${encoderConfig.dtype})`);

const started = Date.now();
const { file } = await trainCentroids({
  encoder,
  encoderConfig,
  phrases: train,
  version,
  centered: true,
  batchSize: 64,
  onProgress: (done, total) => {
    if (done % 512 === 0 || done === total) {
      process.stdout.write(`\r  embedding ${done}/${total}`);
    }
  },
});
process.stdout.write('\n');
console.log(`trained : ${((Date.now() - started) / 1000).toFixed(1)}s, dim ${file.dim}`);

for (const [decision, spec] of Object.entries(file.decisions)) {
  console.log(`  ${decision}: ${spec.labels.length} labels`);
}

await writeFile(join(ROOT, 'models', 'centroids.json'), `${JSON.stringify(file, null, 1)}\n`);

const provenance = {
  _comment: [
    'What the committed centroids were built from. Regenerated by',
    'scripts/train-centroids.mjs; never hand-edited. The point is that a',
    'number in semantic-config.json can be traced to an encoder revision and',
    'a phrase count, not to somebody’s afternoon.',
  ],
  built_at: file.built_at,
  centroids_version: file.version,
  encoder: file.encoder,
  encoder_revision: file.encoder_revision,
  encoder_sha256: Object.fromEntries(
    encoderConfig.files.map((entry) => [entry.path, entry.sha256]),
  ),
  languages: [...LANGUAGES],
  generator:
    'src/training/phrases.ts - seeds x templates, no LLM in the loop; ' +
    'the train/holdout split is by template so calibration never sees a ' +
    'phrasing the centroids were built from',
  splits: {
    train: { phrases: train.length, counts: phraseCounts(train) },
    holdout: { phrases: holdout.length, counts: phraseCounts(holdout) },
  },
  authors: ['flowstarter-sigma-generator'],
};
await writeFile(
  join(ROOT, 'models', 'provenance.json'),
  `${JSON.stringify(provenance, null, 2)}\n`,
);

const bytes = readFileSync(join(ROOT, 'models', 'centroids.json')).length;
console.log(`wrote   : models/centroids.json (${(bytes / 1024).toFixed(0)} KB), models/provenance.json`);
console.log('next    : pnpm --filter @flowstarter/sigma-flowstarter calibrate');
