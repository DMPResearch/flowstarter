#!/usr/bin/env node
/**
 * Points flowstarter-main's local dev server at the Supabase CLI stack,
 * automatically, instead of a developer hand-editing `.env.local` every time
 * the stack restarts and its demo keys rotate.
 *
 * Runs `supabase status -o env`, and writes
 * `apps/flowstarter-main/.env.development.local` with the four values that
 * matter for local dev: `FLOWSTARTER_ENV=development` (so the target guard in
 * `src/lib/supabase-target.ts` knows this is dev, not a hosted build) and the
 * URL/anon key/service-role key the CLI just reported.
 *
 * Usage:
 *   node scripts/supabase-local-env.mjs           # write the file
 *   node scripts/supabase-local-env.mjs --print    # show what would be
 *                                                   # written (masked), don't write
 *
 * `pnpm db:env` runs this. `pnpm dev:supabase` runs `db:start` then this.
 */
import { spawnSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_PATH = join(
  REPO_ROOT,
  'apps/flowstarter-main/.env.development.local',
);

const PRINT_ONLY = process.argv.includes('--print');

/** First 8 characters of a secret, for a log line that never repeats the whole thing. */
function maskKey(value) {
  if (!value) return '(missing)';
  return `${value.slice(0, 8)}... (${value.length} chars)`;
}

/** Parses `KEY="value"` lines from `supabase status -o env` stdout. */
function parseEnvOutput(text) {
  const values = {};
  for (const line of text.split('\n')) {
    const match = /^([A-Z0-9_]+)="(.*)"$/.exec(line);
    if (!match) continue;
    values[match[1]] = match[2];
  }
  return values;
}

function fail(message) {
  console.error(message);
  console.error('Run `pnpm db:start` first, then try again.');
  process.exit(2);
}

function main() {
  const result = spawnSync('supabase', ['status', '-o', 'env'], {
    cwd: REPO_ROOT,
    encoding: 'utf8',
  });

  if (result.error) {
    fail(`Could not run \`supabase status\`: ${result.error.message}`);
  }
  if (result.status !== 0) {
    fail(
      `\`supabase status -o env\` exited with code ${result.status}. ` +
        (result.stderr?.trim() ||
          'The local stack does not look like it is running.'),
    );
  }

  const parsed = parseEnvOutput(result.stdout ?? '');
  const apiUrl = parsed.API_URL;
  const anonKey = parsed.ANON_KEY;
  const serviceRoleKey = parsed.SERVICE_ROLE_KEY;

  if (!apiUrl || !anonKey || !serviceRoleKey) {
    fail(
      '`supabase status -o env` did not report API_URL, ANON_KEY and ' +
        'SERVICE_ROLE_KEY. The local stack does not look like it is running.',
    );
  }

  console.log(`API_URL:            ${apiUrl}`);
  console.log(`ANON_KEY:           ${maskKey(anonKey)}`);
  console.log(`SERVICE_ROLE_KEY:   ${maskKey(serviceRoleKey)}`);

  if (PRINT_ONLY) {
    console.log(`\n--print: not writing ${OUT_PATH}`);
    return;
  }

  const contents = `\
# Generated by \`pnpm db:env\` (scripts/supabase-local-env.mjs). Do not edit
# by hand; it is regenerated from \`supabase status\` every time that script
# runs, and gitignored (see .gitignore's \`.env.*\` rule).
#
# Next.js loads this file for \`next dev\` above \`.env.local\`, so it wins
# over anything the same variable names hold there.
FLOWSTARTER_ENV=development
NEXT_PUBLIC_SUPABASE_URL=${apiUrl}
NEXT_PUBLIC_SUPABASE_ANON_KEY=${anonKey}
SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}
SUPABASE_PROJECT_REF=
`;

  writeFileSync(OUT_PATH, contents);
  console.log(`\nWrote ${OUT_PATH}`);
}

main();
